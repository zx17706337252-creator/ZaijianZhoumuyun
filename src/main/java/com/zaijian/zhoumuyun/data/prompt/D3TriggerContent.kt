    /**
     * 取某个角色在某槎位、第 [attemptNumber] 次提问时，应该注入 system prompt 的
     * 情境化指令文本（场景 + 切入方式 + 语气 + 禁忌，原文是怎么分段就怎么保留）。
     *
     * @param attemptNumber 第几次问这个槎位，从 1 开始计数。
     *        超出文档已写次数时（比如某槎位文档只设计了 3 次，又问了第 4 次），
     *        fallback 复用第 3 次（强制锁定前）的文案——"已经到了临产前脆弱
     *        状态"这件事不会随着问的次数继续往后变化，复用比报错更合理。
     * @return 找不到对应角色/槎位组合时返回 null。characterId 取值 1~6、
     *        questionType 取值 NAME_PREF/WORLDVIEW/WORRY/PERSONA、
     *        WORLDVIEW 与 PERSONA 的 slotIndex 取值 0~1、WORRY 与 NAME_PREF
     *        的 slotIndex 固定按 0 存储——这套组合应该全覆盖，返回 null
     *        多半说明调用方传参有误，不是文案缺失。
     */
    fun blockFor(
        characterId: Int,
        questionType: PregnancyQuestionType,
        slotIndex: Int,
        attemptNumber: Int,
    ): String? {
        val charData = TRIGGER_DATA[characterId]
        // 对于不在 TRIGGER_DATA 中的角色（如第二代女儿，id >= 1000），
        // 使用通用 fallback 文案，确保 D3 提问能正常注入
        if (charData == null) {
            return fallbackBlockFor(questionType, slotIndex, attemptNumber)
        }
        val key = "${questionType.name}_${if (questionType == PregnancyQuestionType.NAME_PREF || questionType == PregnancyQuestionType.WORRY) 0 else slotIndex}"
        val attempts = charData[key] ?: return null
        val maxAttempt = attempts.keys.maxOrNull() ?: return null
        val effectiveAttempt = attemptNumber.coerceIn(1, maxAttempt)
        return attempts[effectiveAttempt]
    }

    /**
     * 通用 D3 触发文案 fallback（用于 TRIGGER_DATA 中没有的角色，如第二代女儿）。
     * 确保女儿角色也能走完 D3→D4→D5 完整链路。
     */
    private fun fallbackBlockFor(
        questionType: PregnancyQuestionType,
        slotIndex: Int,
        attemptNumber: Int,
    ): String? {
        val prompt = when (questionType) {
            PregnancyQuestionType.NAME_PREF ->
                "（她似乎在想一个名字…）「如果要给未来的孩子取个名字，你觉得什么好？」"
            PregnancyQuestionType.WORLDVIEW ->
                if (slotIndex == 0) "（聊到世界观时…）「你觉得这个世界最重要的是什么？」"
                else "（深入聊聊…）「如果可以改变一件事，你想改变什么？」"
            PregnancyQuestionType.WORRY ->
                "（她欲言又止…）「其实我一直有些担心…你愿意听吗？」"
            PregnancyQuestionType.PERSONA ->
                if (slotIndex == 0) "（聊到性格时…）「你觉得我是一个什么样的人？」"
                else "（若有所思…）「在你眼中，我和别人有什么不同？」"
        }
        // 第 2、3 次提问用稍有不同的措辞
        return when (attemptNumber) {
            1    -> prompt
            2    -> "$prompt\n（再次提起…）"
            else -> "$prompt\n（第三次提起…）"
        }
    }

