// v42 修正：本轮改用顶点+右下角两点法逐个重测（顶点x即为
// cx，w=(右下角x-顶点x)×2，h=右下角y-顶点y，cy=顶点y+h/2），
// 覆盖 8 个角色（除莫婉凝外全部，2026-07-06 对话，历时多轮
