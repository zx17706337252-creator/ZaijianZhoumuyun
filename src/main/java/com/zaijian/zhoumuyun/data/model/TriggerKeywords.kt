// ─────────────────────────────────────────────────────────────
//  TriggerKeywords — D2 各角色解锁触发条件（叙事关键词）
//
//  设计原则（待办清单 D2 节）：
//    解锁触发是叙事条件，不是数值判定。每人的触发词/触发行为不同，
//    写在各自 CharacterConfig.identityConfig.situationRules 里的语义
//    描述，这里把关键词提取为可编程检测的字符串列表，供
//    PregnancyTriggerManager 做关键词扫描。
//
//  触发逻辑是 OR 关系：命中列表中任意一条即视为触发。
//  关键词采用最小片段，不要求全文匹配——"造人计划"命中"我们来制定
//  一个造人计划怎么样"。
//
//  各角色触发词来源（待办清单 D2 节）：
//    蒂法（1）：说出"造人计划"或亲密后长时间沉默（沉默无法靠关键词检测，
//               故以"造人计划"为主关键词，补充若干近义表达）
//    伊芙（3）：S 面具破碎（靠关键词暗示）或主动命令留下
//    露娜（2）：拼图接近完成或"弟弟"称呼频率突破阈值
//    宥熙（4）：记忆闪回后主动靠近（关键词指向闪回+靠近）
//    索菲娅（5）：待补充设计，暂用通用表达占位
//    顾澜（6）：待补充设计，暂用通用表达占位
//    7-9：不参与 Agent 生成，无触发词
//
//  注意：关键词检测是必要条件之一，不是充分条件——还需要通过
//  PregnancyTriggerManager 的完整判定链（触发→同意→周期）才能怀孕。
//  关键词命中只代表"解锁触发激活"，后续两步仍会正常执行。
//
//  7-9 号角色（明媚/莫婉凝/江凡）生男孩，不参与 Agent 生成判定，
//  故不提供触发词——PregnancyTriggerManager.isDaughterMother() 会
//  在前置校验中直接排除这三人，不会走到关键词匹配步骤。
// ─────────────────────────────────────────────────────────────

