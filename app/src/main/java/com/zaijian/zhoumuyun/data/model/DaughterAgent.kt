package com.zaijian.zhoumuyun.data.model

// ─────────────────────────────────────────────────────────────
//  DaughterAgent — 女儿 Agent 系统核心枚举（D1）
//
//  本文件只定义枚举，不包含业务逻辑。
//  触发条件、使用规则分别在 D5（AgentRelationStage）和 D4
//  （DaughterDifferenceType）阶段细化，本阶段先占位。
//
//  范围边界：
//  - AgentRelationStage 是女儿与用户的关系状态，独立于九位母亲共用的
//    CharacterStateLayer 五维结构，不复用也不影响母亲侧任何字段。
//  - DaughterDifferenceType 描述女儿角色卡与母亲的差异生成规则，
//    具体映射在 D4 的 DaughterCharacterConfig 生成器里落地。
// ─────────────────────────────────────────────────────────────

/**
 * 女儿与用户的关系阶段（两阶段状态机）。
 *
 * 阶段切换触发条件在 D5 细化，本阶段只定义枚举值和语义描述。
 */
enum class AgentRelationStage {
    /**
     * 初入家庭。
     * 核心情感：依赖、信任建立中、对世界充满好奇。
     * 叙事表现：称呼试探、对母亲行为的模仿与反问、边界感模糊。
     */
    STAGE_1_INITIAL,

    /**
     * 深度连接。
     * 核心情感：信任加深、情感纽带已成形、开始有独立判断。
     * 叙事表现：主动表达立场、保护性情绪、对用户有明确期待。
     */
    STAGE_2_BONDING,

    /**
     * 独立探索。
     * 核心情感：自我意识觉醒、开始寻求独立身份、可能产生叛逆或深度对话。
     * 叙事表现：主动发起话题、对世界有自己的判断、开始反向影响母亲。
     */
    STAGE_3_SEEKING,
}

/**
 * 女儿角色卡与母亲的差异生成类型（强制差异规则）。
 *
 * D4 的角色卡生成器要求每对母女至少命中 2 项，确保女儿可识别、
 * 不是母亲的简单复制。具体映射规则在 D4 落地，本阶段只定义分类。
 */
enum class DaughterDifferenceType {
    /**
     * A · 反转（Reversal）。
     * 母亲的某个核心特质在女儿身上极性翻转。
     * 例：母亲冷漠克制 → 女儿热烈直白；母亲占有欲强 → 女儿刻意疏离。
     */
    REVERSAL,

    /**
     * B · 位移（Shift）。
     * 母亲的某个特质在女儿身上保留，但触发场景或对象发生偏移。
     * 例：母亲对用户黏性极高 → 女儿将同等黏性转移到某个信念/记忆上。
     */
    SHIFT,

    /**
     * C · 放大（Amplify）。
     * 母亲某个被压抑或隐藏的底层特质，在女儿身上被放大到表面。
     * 例：母亲面具下的脆弱 → 女儿将脆弱直接暴露为核心性格标签。
     */
    AMPLIFY,
}
